const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const files = {
  'Sophia Calabrese': 'sophia-calabrese.jpg',
  'Michael Williams': 'michael-williams.jpg',
  'Kenzie Wright': 'kenzie-wright.jpg',
};
const images = Object.fromEntries(Object.entries(files).map(([name, file]) => [
  name, 'data:image/jpeg;base64,' + fs.readFileSync(path.join(root, 'assets/reporters', file)).toString('base64'),
]));
fs.writeFileSync(path.join(root, 'assets/reporters/reporter-images.js'),
  '// User-supplied interview illustrations, November 6, 2026. Original JPEGs preserved.\n' +
  '// Generated by tools/pack_reporter_images.cjs.\n' +
  'const SC_REPORTER_IMAGES = ' + JSON.stringify(images, null, 2) + ';\n');
