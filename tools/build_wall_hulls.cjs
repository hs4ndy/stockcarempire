// Derive compact collision support points from the shipped car geometry.
const fs=require('node:fs'),vm=require('node:vm'),THREE=require('three');
const c=vm.createContext({THREE});
vm.runInContext(fs.readFileSync('node_modules/three/examples/js/math/ConvexHull.js','utf8'),c);
for(const f of ['stock-car-model','legacy-stock-car-model'])vm.runInContext(fs.readFileSync(`assets/cars/${f}.js`,'utf8'),c);
const models=vm.runInContext('[SC_LEGACY_STOCK_CAR_MODEL,SC_STOCK_CAR_MODEL]',c),out={};
models.forEach((m,i)=>{
 const points=[],sx=i===0?.91:1,sz=i===0?.9:1;
 const add=(p,offset=[0,0,0])=>{for(let j=0;j<p.length;j+=3)points.push(new THREE.Vector3((p[j]+offset[0])*sx,p[j+1]+offset[1],(p[j+2]+offset[2])*sz));};
 Object.values(m.parts).forEach(part=>add(part.position));m.wheelPositions.forEach(offset=>add(m.wheel.position,offset));
 const hull=new THREE.ConvexHull().setFromPoints(points),vertices=new Map();
 for(const face of hull.faces){let edge=face.edge;do{const p=edge.head().point;vertices.set(`${p.x},${p.y},${p.z}`,[p.x,p.y,p.z]);edge=edge.next;}while(edge!==face.edge);}
 out[i===0?'grassroots':'gen7']=[...vertices.values()].flat();
 console.log(m.name,vertices.size,'hull points from',points.length,'vertices');
});
fs.writeFileSync('assets/cars/wall-contact-hulls.js','// Generated by tools/build_wall_hulls.cjs from runtime body/wheel meshes.\nconst SC_WALL_HULLS = '+JSON.stringify(out)+';\n');
