const {test,expect}=require('playwright/test');
const path=require('node:path'); const {pathToFileURL}=require('node:url');
for(const width of [1440,375]) test(`career refinements and race rollback ${width}`,async({page})=>{
 await page.setViewportSize({width,height:850});
 await page.route('**/three.min.js',r=>r.fulfill({path:path.resolve('node_modules/three/build/three.min.js')}));
 await page.goto(pathToFileURL(path.resolve('releases/Stock-Car-Empire.html')).href);
 await page.evaluate(()=>{newGame('Test Team','Driver','Car');game.tutorial.status='skipped';game.currentSeries=2;game.season.aiTeams=generateAITeams(2);rebuildStandings();game.money=500000;saveToSlot(3);enterGame();showTab('market');});
 await page.getByRole('button',{name:'Loans and Financing',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Take out a loan'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:`.impeccable/review/loans-${width}.png`});
 await page.evaluate(()=>{window.beforeRace=JSON.stringify(game);handleStartRace();});
 await page.waitForFunction(()=>window._r3d?.mirrorRT);
 expect(await page.evaluate(()=>window._r3d.cars.length)).toBe(40);
 await page.locator('#r3d-pause-btn').click();
 await expect(page.locator('#r3d-quit')).toBeVisible();
 await page.screenshot({path:`.impeccable/review/quit-${width}.png`});
 await page.locator('#r3d-quit').click();
 expect(await page.evaluate(()=>JSON.stringify(game)===window.beforeRace)).toBe(true);
 expect(await page.evaluate(()=>localStorage.getItem('sce_slot_3')===window.beforeRace)).toBe(true);
 await page.evaluate(()=>{showTab('carstats');});
 await expect(page.locator('#main-content')).not.toContainText('Driver / Owner');
 await page.evaluate(()=>{game.money=0;handleStartRace();});
 await expect(page.locator('#toast-container')).toContainText('Take out a loan');
 await page.evaluate(()=>{game.tutorial.status='in-progress';careerTutorialStep=CAREER_TUTORIAL_STEPS.findIndex(s=>s.title==='Borrow with a repayment plan');renderCareerTutorialStep();});
 await expect(page.locator('#career-tutorial-title')).toHaveText('Borrow with a repayment plan');
 await page.locator('[data-tutorial-action="next"]').click();
 await expect(page.locator('#career-tutorial-title')).toHaveText('Understand debt and credit');
});
